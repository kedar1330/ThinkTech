import { z } from 'zod';
import { objectIdSchema, slotIdSchema } from './common';
import { photoContentTypeSchema } from './photos';

// Design Studio (D-134, approved 2026-10-23; stages this part of D-76). The user draws a sketch, uploads a sketch or a
// picture of a garment, describes an idea, or starts from one of their looks and says what to change.
// Gemini turns that into a garment-only image prompt and a tailor's specification; Pollinations (FLUX)
// draws the design from the text prompt, with Cloudflare Workers AI (FLUX) as the fallback. The image
// services receive only that garment description, never the user's picture or profile.

/** Where a design started. `look` is a look from Discover My Style with the user's requested changes. */
export const DESIGN_SOURCES = ['sketch', 'upload', 'description', 'look'] as const;
export const designSourceSchema = z.enum(DESIGN_SOURCES);
export type DesignSource = z.infer<typeof designSourceSchema>;

/** Version of the Design Studio notice the user agrees to before each design; bump it when the wording changes. */
export const DESIGN_NOTICE_VERSION = '2026-10-23.1';
/** The web app shrinks sketches before upload; the API refuses anything larger. */
export const DESIGN_IMAGE_MAX_BYTES = 4 * 1024 * 1024;
export const DESIGN_DESCRIPTION_MAX = 1200;
/** Designs kept per user; the user deletes old ones to make more. */
export const DESIGN_LIMIT_PER_USER = 50;
/**
 * Content type of `POST /v1/design-studio/designs`. The JSON carries a base64 sketch, so it has its own
 * type and size limit instead of the global 16 kB JSON limit.
 */
export const DESIGN_REQUEST_CONTENT_TYPE = 'application/vnd.styleme.design+json';

const BASE64_MAX = Math.ceil(DESIGN_IMAGE_MAX_BYTES / 3) * 4;

export const createDesignRequestSchema = z
  .object({
    source: designSourceSchema,
    /** What the user imagines, or for a look, what to change. Never their measurements or other personal details. */
    description: z.string().trim().max(DESIGN_DESCRIPTION_MAX).default(''),
    /** A drawn or uploaded sketch, or a picture of a garment (sketch and upload only). */
    image: z
      .object({ contentType: photoContentTypeSchema, base64: z.string().min(1).max(BASE64_MAX) })
      .strict()
      .optional(),
    /** The look to start from (source `look`). */
    lookId: objectIdSchema.optional(),
    /** Optional: the one piece of the look to change; the rest stays as it is. */
    slotId: slotIdSchema.optional(),
    notice: z.literal(DESIGN_NOTICE_VERSION),
  })
  .strict()
  .superRefine((req, ctx) => {
    const usesImage = req.source === 'sketch' || req.source === 'upload';
    if (usesImage !== Boolean(req.image))
      ctx.addIssue({ code: 'custom', path: ['image'], message: usesImage ? 'Add a sketch or picture' : 'Not allowed' });
    if ((req.source === 'look') !== Boolean(req.lookId))
      ctx.addIssue({ code: 'custom', path: ['lookId'], message: 'Only for a look' });
    if (req.slotId && req.source !== 'look')
      ctx.addIssue({ code: 'custom', path: ['slotId'], message: 'Only for a look' });
    if (req.source === 'description' && req.description.length < 10)
      ctx.addIssue({ code: 'custom', path: ['description'], message: 'Describe your idea in a few words' });
    if (req.source === 'look' && req.description.length < 3)
      ctx.addIssue({ code: 'custom', path: ['description'], message: 'Say what you would like to change' });
  });
export type CreateDesignRequest = z.input<typeof createDesignRequestSchema>;

// --- Tailor specification (generated by Gemini, validated by the API) ------------------------------

const line = z.string().trim().min(1).max(300);

export const tailorSpecSchema = z
  .object({
    garment: line,
    silhouette: line,
    neckline: line,
    sleeves: line,
    length: line,
    closure: line,
    fabric: z.object({ primary: line, alternatives: z.array(line).max(4), lining: line }).strict(),
    /** An estimate for a standard adult size; the tailor confirms it with the wearer's own measurements. */
    yardage: z.object({ estimate: line, basis: line }).strict(),
    cutting: z.array(line).min(1).max(10),
    stitching: z.array(line).min(1).max(12),
    finishing: z.array(line).max(8),
    embellishment: z.array(line).max(8),
    tailorNotes: z.array(line).max(8),
  })
  .strict();
export type TailorSpec = z.infer<typeof tailorSpecSchema>;

// --- Responses -------------------------------------------------------------------------------------

/** `ready`: the design picture exists. `failed`: every image service failed; the spec is kept and the picture can be retried. */
export const DESIGN_IMAGE_STATUSES = ['ready', 'failed'] as const;
export type DesignImageStatus = (typeof DESIGN_IMAGE_STATUSES)[number];

export const DESIGN_IMAGE_PROVIDERS = ['pollinations', 'cloudflare'] as const;
export type DesignImageProvider = (typeof DESIGN_IMAGE_PROVIDERS)[number];

export interface DesignSummary {
  id: string;
  title: string;
  source: DesignSource;
  imageStatus: DesignImageStatus;
  hasSourceImage: boolean;
  createdAt: string;
}

export interface Design extends DesignSummary {
  description: string;
  summary: string;
  lookId: string | null;
  tailorSpec: TailorSpec;
  imageProvider: DesignImageProvider | null;
  /** Changes when the picture is drawn again, so the page can request the new one. */
  updatedAt: string;
}

/** `GET /v1/design-studio`: the user's designs (newest first) and whether the studio can run. */
export interface DesignStudioResponse {
  /** Gemini is configured and the studio is switched on. */
  available: boolean;
  /** At least one image service is configured. Without one, designs get a tailor spec but no picture. */
  imagesAvailable: boolean;
  designs: DesignSummary[];
  limit: number;
}

/** Shown when Gemini can't use the input; the user tries again with a clearer sketch or description. */
export const DESIGN_UNUSABLE_REASONS = ['not_a_garment', 'shows_person', 'unclear'] as const;
export type DesignUnusableReason = (typeof DESIGN_UNUSABLE_REASONS)[number];
export const DESIGN_UNUSABLE_MESSAGES: Record<DesignUnusableReason, string> = {
  not_a_garment: 'We couldn’t find a garment to design from. Try a clearer sketch, or describe the outfit in words.',
  shows_person:
    'Please don’t upload photos of people. Use a sketch or a picture of the garment on its own, or describe it.',
  unclear: 'We couldn’t make out the design. Add a few words about the garment, its neckline, sleeves and length.',
};
