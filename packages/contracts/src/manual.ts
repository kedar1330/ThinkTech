import { z } from 'zod';

export const MANUAL_STEP_STATUSES = ['live', 'preview'] as const;
export type ManualStepStatus = (typeof MANUAL_STEP_STATUSES)[number];

export const manualStepSchema = z
  .object({
    id: z.string().optional(),
    stepNumber: z.number().int().min(1).max(20),
    slug: z.string().trim().min(1),
    title: z.string().trim().min(1),
    tagline: z.string().trim().min(1),
    description: z.string().trim().min(1),
    actionLabel: z.string().trim().min(1),
    actionHref: z.string().trim().min(1),
    imageUrl: z.string().trim().min(1),
    imageData: z.string().optional(),
    imageAlt: z.string().trim().min(1),
    highlights: z.array(z.string().trim().min(1)).min(1),
    category: z.string().trim().min(1),
    status: z.enum(MANUAL_STEP_STATUSES),
    sortOrder: z.number().int(),
  })
  .strict();

export type ManualStep = z.infer<typeof manualStepSchema>;

export const manualStepsResponseSchema = z
  .object({
    steps: z.array(manualStepSchema),
  })
  .strict();

export type ManualStepsResponse = z.infer<typeof manualStepsResponseSchema>;

