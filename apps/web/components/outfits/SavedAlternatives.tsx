'use client';

import { useActionState } from 'react';
import { RefreshCw, Sparkles } from 'lucide-react';
import { CATEGORIES, type LookSlot } from '@styleme/contracts';
import { getFreshAlternativesAction } from '@/app/actions/outfits';
import { Alert } from '@/components/ui/alert';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Spinner } from '@/components/ui/spinner';
import { slotLabel, vocabLabel } from '@/lib/outfits/look-text';
import { SlotAlternatives } from './SlotAlternatives';

interface SavedAlternativesProps {
  outfitId: string;
  slots: readonly LookSlot[];
}

export function SavedAlternatives({ outfitId, slots }: SavedAlternativesProps) {
  const [state, action, pending] = useActionState(getFreshAlternativesAction, undefined);
  const activeSlots = state?.slots ?? slots;
  const isFresh = Boolean(state?.slots);

  return (
    <section aria-labelledby="saved-alternatives-heading" className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <h2 id="saved-alternatives-heading" className="font-display text-2xl text-primary">
              Alternatives for this look
            </h2>
            {isFresh && (
              <Badge className="inline-flex items-center gap-1 border-success/40 bg-success/10 text-success">
                <Sparkles aria-hidden className="size-3" />
                Fresh from engine
              </Badge>
            )}
          </div>
          <p className="mt-1 text-sm text-muted-foreground">
            {isFresh
              ? 'Fresh alternatives generated by the engine using your current profile and feedback signals.'
              : 'Stored variations for each slot saved with this look.'}
          </p>
        </div>

        <form action={action}>
          <input type="hidden" name="outfitId" value={outfitId} />
          <Button
            type="submit"
            variant="outline"
            disabled={pending}
            className="inline-flex min-h-10 items-center gap-2 text-xs font-medium"
          >
            {pending ? <Spinner className="size-3.5" /> : <RefreshCw aria-hidden className="size-3.5" />}
            {pending ? 'Getting fresh alternatives…' : 'Get fresh alternatives'}
          </Button>
        </form>
      </div>

      {state?.error && <Alert tone="error">{state.error}</Alert>}

      <ol className="grid gap-4 sm:grid-cols-2">
        {activeSlots.map((slot) => (
          <li key={slot.slotId}>
            <Card className="h-full space-y-3 p-5">
              <div className="space-y-1">
                <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">
                  {slotLabel(slot.slot)}
                </p>
                <h3 className="font-medium text-primary">{vocabLabel(CATEGORIES, slot.lookSpec.category)}</h3>
              </div>
              <SlotAlternatives alternatives={slot.alternatives} />
            </Card>
          </li>
        ))}
      </ol>
    </section>
  );
}
