const configSchema = envSchema.superRefine((env, ctx) => {
  if (env.OUTFIT_IMAGES_ENABLED) {
    if (env.APP_ENV === 'staging') {
      ctx.addIssue({
        code: 'custom',
        path: ['OUTFIT_IMAGES_ENABLED'],
        message: 'OUTFIT_IMAGES_ENABLED can be switched on only locally',
      });
    }
    const hasCloudflare =
      (env.CLOUDFLARE_ACCOUNT_ID && env.CLOUDFLARE_API_TOKEN) ||
      (env.CLOUDFLARE_ACCOUNT_ID_2 && env.CLOUDFLARE_API_TOKEN_2);
    const canUsePollinationsForOutfits = env.POLLINATIONS_API_KEY && !env.POLLINATIONS_TRY_ON_ONLY;
    if (!canUsePollinationsForOutfits && !hasCloudflare) {
      ctx.addIssue({
        code: 'custom',
        path: ['POLLINATIONS_API_KEY'],
        message: 'required when OUTFIT_IMAGES_ENABLED=true unless Cloudflare is configured',
      });
    }
  }
  if (!env.AI_WORDING_ENABLED) return;
  for (const name of ['GEMINI_API_KEY', 'GEMINI_MODEL'] as const) {
    if (!env[name]) ctx.addIssue({ code: 'custom', path: [name], message: 'required when AI_WORDING_ENABLED=true' });
  }
});

import fs from 'node:fs';
import path from 'node:path';

function loadDotenvFiles(): Record<string, string> {
  const candidates = [
    path.resolve(process.cwd(), '.env'),
    path.resolve(process.cwd(), 'apps/api/.env'),
    '/etc/secrets/.env',
    path.resolve(process.cwd(), '/etc/secrets/.env'),
  ];
  for (const file of candidates) {
    try {
      if (fs.existsSync(file)) {
        const text = fs.readFileSync(file, 'utf8');
        for (const line of text.split(/\r?\n/)) {
          const trimmed = line.trim();
          if (!trimmed || trimmed.startsWith('#')) continue;
          const idx = trimmed.indexOf('=');
          if (idx > 0) {
            const k = trimmed.slice(0, idx).trim();
            let v = trimmed.slice(idx + 1).trim();
            if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
              v = v.slice(1, -1);
            }
            if (!result[k]) result[k] = v;
          }
        }
      }
    } catch {
      // ignore
    }
  }
  return result;
}

export type Config = z.infer<typeof envSchema>;

export function loadConfig(env: NodeJS.ProcessEnv = process.env): Config {
  const fileEnv = loadDotenvFiles();
  const merged = { ...fileEnv, ...env };
  const parsed = configSchema.safeParse(merged);
  if (!parsed.success) {
    // Report variable names only, never values.
    const names = parsed.error.issues.map((i) => i.path.join('.')).join(', ');
    throw new Error(`Invalid or missing environment variables: ${names}`);
  }
  return parsed.data;
}

