import { z } from 'zod';

// Environment configuration (DEPLOYMENT.md §3.1). Parsed once at startup; the process exits on invalid config.

const bool = z
  .enum(['true', 'false'])
  .default('false')
  .transform((v) => v === 'true');

const optional = z
  .string()
  .optional()
  .transform((v) => (v && v.trim() !== '' ? v.trim() : undefined));

